CREATE TABLE IF NOT EXISTS candidate_sequence (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  next_value INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'student'
    CHECK (role IN ('student', 'admin')),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  candidate_no TEXT
);

CREATE TABLE IF NOT EXISTS portal_admins (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  totp_secret TEXT NOT NULL,
  active INTEGER NOT NULL DEFAULT 1,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS portal_admin_audit (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  admin_id INTEGER,
  action TEXT NOT NULL,
  detail TEXT DEFAULT '',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS it_study_materials (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chapter TEXT NOT NULL,
  title TEXT NOT NULL,
  description TEXT DEFAULT '',
  content TEXT DEFAULT '',
  file_url TEXT DEFAULT '',
  material_type TEXT NOT NULL DEFAULT 'Notes',
  sort_order INTEGER NOT NULL DEFAULT 0,
  is_published INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS it_practice_questions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chapter TEXT NOT NULL,
  question TEXT NOT NULL,
  options_json TEXT NOT NULL,
  correct_option TEXT NOT NULL CHECK (correct_option IN ('A','B','C','D')),
  explanation TEXT DEFAULT '',
  is_published INTEGER NOT NULL DEFAULT 0,
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS student_exam_papers (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  subject TEXT NOT NULL DEFAULT 'Information Technology',
  duration_minutes INTEGER NOT NULL DEFAULT 150,
  total_marks INTEGER NOT NULL DEFAULT 80,
  exam_date TEXT NOT NULL,
  is_published INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS student_exam_questions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  paper_id INTEGER NOT NULL REFERENCES student_exam_papers(id),
  question TEXT NOT NULL,
  options_json TEXT NOT NULL,
  correct_option TEXT NOT NULL CHECK (correct_option IN ('A','B','C','D')),
  marks INTEGER NOT NULL DEFAULT 1,
  explanation TEXT DEFAULT ''
);

CREATE TABLE IF NOT EXISTS student_exam_attempts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  paper_id INTEGER NOT NULL REFERENCES student_exam_papers(id),
  user_id INTEGER NOT NULL,
  started_at TEXT NOT NULL,
  deadline_at TEXT NOT NULL,
  submitted_at TEXT,
  answers_json TEXT NOT NULL DEFAULT '{}',
  score INTEGER,
  grading_complete INTEGER NOT NULL DEFAULT 1,
  UNIQUE (paper_id, user_id)
);

CREATE TABLE IF NOT EXISTS portal_written_questions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  paper_id INTEGER NOT NULL,
  chapter TEXT NOT NULL DEFAULT '',
  question TEXT NOT NULL,
  expected_answer TEXT DEFAULT '',
  rubric TEXT NOT NULL,
  marks INTEGER NOT NULL DEFAULT 1,
  language TEXT NOT NULL DEFAULT 'Theory',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
